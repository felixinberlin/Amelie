export type FundingStatus = 'opens-soon' | 'open' | 'closing' | 'closed' | 'rolling' | 'paused' | 'cycle' | 'resource';

const DAY = 86_400_000;

function ms(iso: string): number {
  return new Date(`${iso}T23:59:59`).getTime();
}

export function daysUntil(iso: string, now: Date = new Date()): number {
  const diff = ms(iso) - now.getTime();
  return diff < 0 ? Math.floor(diff / DAY) : Math.ceil(diff / DAY);
}

/** Berechnet den Anzeigestatus zur Laufzeit, damit abgelaufene Fristen nie als offen erscheinen. */
export function fundingStatus(item: FundingItem, now: Date = new Date()): FundingStatus {
  if (item.timing === 'resource') return 'resource';
  if (item.timing === 'rolling') return 'rolling';
  if (item.timing === 'paused') return 'paused';
  if (item.deadline) {
    if (now.getTime() > ms(item.deadline)) return item.timing === 'cycle' ? 'cycle' : 'closed';
    if (item.opens && new Date(`${item.opens}T00:00:00`).getTime() > now.getTime()) return 'opens-soon';
    const left = daysUntil(item.deadline, now);
    return left <= 30 ? 'closing' : 'open';
  }
  return 'cycle';
}

