export type FundingCategory =
  | 'oss'
  | 'civil'
  | 'eu'
  | 'prize'
  | 'city'
  | 'venture'
  | 'payment';

export type FundingTiming = 'dated' | 'rolling' | 'paused' | 'cycle' | 'resource';
export type FundingApplicant = 'individual' | 'ngo' | 'municipality' | 'startup' | 'university';
export type FundingTopic =
  | 'nature'
  | 'consumer'
  | 'mobility'
  | 'energy'
  | 'admin'
  | 'science'
  | 'democracy'
  | 'infrastructure'
  | 'work'
  | 'knowledge';

export interface FundingItem {
  id: string;
  category: FundingCategory;
  nameDe: string;
  nameEn: string;
  funder: string;
  amountDe: string;
  amountEn: string;
  timing: FundingTiming;
  /** ISO-Datum: Öffnung der Bewerbung (optional). */
  opens?: string;
  /** ISO-Datum: Ende der Frist (bei `dated`). */
  deadline?: string;
  /** Freitext, wann die nächste Runde erwartet wird (bei abgelaufenen oder zyklischen Calls). */
  nextDe?: string;
  nextEn?: string;
  applicants: FundingApplicant[];
  topics: FundingTopic[];
  /** Passung für die Finanzierung einer Amélie-Dose bzw. ihres Empfängers: 0 keine, 3 sehr hoch. */
  fit: 0 | 1 | 2 | 3;
  fitDe: string;
  fitEn: string;
  conditionsDe?: string;
  conditionsEn?: string;
  evidence: 'read' | 'snippet';
  url?: string;
  checked: string;
}

export type FundingEventType = 'deadline' | 'opening' | 'event' | 'pitch';

export interface FundingEvent {
  date: string; // ISO YYYY-MM-DD
  labelDe: string;
  labelEn: string;
  refId?: string;
  type?: FundingEventType;
  descriptionDe?: string;
  descriptionEn?: string;
}

